// Export the existing app logo at Apple's required pass icon sizes.
// No replacement artwork: assets/images/Icon.png remains the source of truth.
const fs = require('node:fs');
const { createCanvas, loadImage } = require('@napi-rs/canvas');
const crypto = require('node:crypto');
(async () => {
  const source = fs.readFileSync('assets/images/Icon.png');
  const image = await loadImage(source);
  const assets = {};
  fs.mkdirSync('assets/wallet-pass/brand', { recursive: true });
  for (const scale of [1, 2, 3]) {
    const name = `icon${scale === 1 ? '' : '@' + scale + 'x'}.png`;
    const size = 29 * scale;
    const canvas = createCanvas(size, size);
    canvas.getContext('2d').drawImage(image, 0, 0, size, size);
    const bytes = canvas.toBuffer('image/png');
    fs.writeFileSync('assets/wallet-pass/brand/' + name, bytes);
    assets[name] = bytes.toString('base64');
  }
  const hash = crypto.createHash('sha256').update(source).digest('hex');
  fs.writeFileSync('supabase/functions/apple-wallet-generator/brandingAssets.ts',
    '// Generated by scripts/build-wallet-branding.cjs from assets/images/Icon.png\n' +
    `export const APP_ICON_SHA256 = '${hash}';\n` +
    'export const WALLET_BRANDING: Record<string, string> = ' + JSON.stringify(assets) + ';\n');
  console.log('Exported Eclipse pass notification icons at 29, 58 and 87 pixels.');
})().catch(error => { console.error(error); process.exitCode = 1; });
