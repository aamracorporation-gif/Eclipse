'use strict';
// Reuse the audited Edge transport in the Node server without a runtime compiler.
const fs = require('node:fs'), path = require('node:path'), ts = require('typescript');
const root = path.resolve(__dirname, '..');
const target = path.join(root, 'backend/src/services/notifications');
fs.mkdirSync(target, { recursive: true });
for (const name of ['notificationDelivery', 'notificationWorkerHealth']) {
  const source = fs.readFileSync(path.join(root, 'supabase/functions/_shared', name + '.ts'), 'utf8');
  const code = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText
    .replace('require("./notificationDelivery.ts")', 'require("./notificationDelivery")');
  const expected = '// Generated by scripts/build-notification-runtime.cjs; edit the shared TypeScript source.\n' + code;
  const file = path.join(target, name + '.js');
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(file, 'utf8') !== expected) throw new Error('Stale notification transport: ' + name);
  } else fs.writeFileSync(file, expected);
}
